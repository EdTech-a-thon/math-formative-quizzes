// Regenerates src/lib/pickerIcons.ts from the `lucide` package (ISC license).
//
// Only the hand-picked set below ships — icons that read like an emoji at a
// glance, so a teacher can label a quiz "the rocket one" and be understood.
// They stay in this order in the picker (grouped, not alphabetical) because a
// short list is nicer to browse by theme than by name.
//
//   bun run generate:icons
import { writeFileSync } from "node:fs";
import { icons } from "lucide";

const picks = [
  // Faces and people
  "smile", "laugh", "annoyed", "heart", "thumbs-up", "hand", "party-popper", "ghost", "bot", "baby",
  // Animals
  "cat", "dog", "bird", "fish", "rabbit", "turtle", "snail", "bug", "squirrel", "panda", "paw-print", "feather",
  // Sky and weather
  "sun", "moon", "cloud", "cloud-rain", "cloud-snow", "snowflake", "rainbow", "star", "sparkles", "zap", "flame", "droplet", "wind", "sunrise",
  // Growing things
  "tree-pine", "tree-deciduous", "flower", "leaf", "sprout", "clover", "mountain", "mountain-snow", "waves", "tent",
  // Food
  "apple", "banana", "cherry", "carrot", "wheat", "pizza", "sandwich", "egg", "cookie", "candy", "croissant", "donut", "cake", "ice-cream-cone", "popcorn", "coffee", "cup-soda", "milk", "soup", "salad", "utensils",
  // Going places
  "rocket", "plane", "car", "bus", "bike", "train-front", "ship", "sailboat", "anchor", "map", "compass", "flag",
  // Play
  "trophy", "medal", "crown", "gem", "gift", "balloon", "puzzle", "gamepad-2", "dice-5", "target", "music", "headphones", "guitar", "drum", "toy-brick", "blocks", "shapes",
  // School and making
  "book", "book-open", "backpack", "pencil", "paintbrush", "palette", "scissors", "ruler", "calculator", "graduation-cap", "lightbulb", "microscope", "telescope", "magnet", "hammer", "wrench",
  // Everyday things
  "house", "castle", "bell", "key", "lock", "clock", "hourglass", "umbrella", "glasses", "shirt", "camera", "battery", "shield", "wand-sparkles", "piggy-bank", "coins",
];

const pascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, character) => character.toUpperCase());

const escape = (value) => String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const toMarkup = (node) =>
  node
    .map(([tag, attributes]) => `<${tag}${Object.entries(attributes).map(([key, value]) => ` ${key}="${escape(value)}"`).join("")}/>`)
    .join("");

const missing = picks.filter((name) => !icons[pascal(name)]);
if (missing.length) throw new Error(`Not in Lucide: ${missing.join(", ")}`);
const duplicates = picks.filter((name, index) => picks.indexOf(name) !== index);
if (duplicates.length) throw new Error(`Listed twice: ${duplicates.join(", ")}`);

const body = picks.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(toMarkup(icons[pascal(name)]))},`).join("\n");

writeFileSync(
  new URL("../src/lib/pickerIcons.ts", import.meta.url),
  `// GENERATED by scripts/generate-lucide-icons.mjs — do not edit by hand.\n` +
    `// A hand-picked, emoji-ish slice of Lucide (https://lucide.dev, ISC license)\n` +
    `// as inner SVG markup, in picker order.\n` +
    `export const pickerIcons: Record<string, string> = {\n${body}\n};\n\n` +
    `export const pickerIconNames = Object.keys(pickerIcons);\n`,
);

console.log(`wrote ${picks.length} icons`);
